def char_width_per_mille(font_name: str, char: str) -> Optional[float]:
    """The AFM-style width (per 1000 units of em) of *char* in
    *font_name* (one of WIDTHS_256PT's own keys), or None if the font
    isn't covered by this table at all, or *char* has no RISC OS
    Latin1 representation (see encoding.encode_byte_or_none -- the
    strict variant, not encode_byte, since that one's own '?'
    fallback would otherwise be indistinguishable here from a genuine
    RISC OS Latin1 '?') -- either way, the caller should fall back to
    an approximate average width instead."""
    table = WIDTHS_256PT.get(font_name)
    if table is None:
        return None
    byte = encoding.encode_byte_or_none(char)
    if byte is None or byte < 32:
        return None
    return table[byte - 32] / 256.0
