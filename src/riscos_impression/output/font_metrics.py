"""Real per-character advance-width metrics for the RISC OS system
fonts Impression documents most commonly use for body text (Trinity,
Homerton), used by pdfdoc.py to lay out and justify text far more
accurately than a single flat per-family average width can.

Reproduced from the independent garethmccaughan-mkdrawf project's own
Font_ScanString emulation table
(https://github.com/gerph/garethmccaughan-mkdrawf, Source/c/
fake_fontscanstring), not derived from the Impression conversion
source. That table gives each character's advance width scanned at a
256pt reference size; dividing by 256 gives the same "width per 1000
units of em" convention Adobe's own AFM font metrics use -- confirmed
by cross-checking Homerton's own values against Helvetica's published
AFM widths, which match exactly (Homerton is RISC OS's Helvetica-
alike; Trinity is RISC OS's Times-alike).

Each table is indexed by RISC OS Latin1 (alphabet 101; see
encoding.py) byte value, not Unicode code point order -- glyphs in the
0x80-0x9F range are RISC OS's own smart quotes/dashes/ligatures/UI
icons, not raw Latin-1 control codes, and this table's own entries in
that range confirm it: they hold real, glyph-appropriate widths for
the printable ones (quotes, dashes, ligatures) and 0 for the handful
with no real text glyph at all (the window resize/close icons, cursor
arrows) -- which is exactly what real RISC OS font metrics for those
code points would give. A caller must go through
encoding.encode_byte() to turn a Unicode character back into the right
table index; see char_width_per_mille().

Corpus (RISC OS's Courier-alike) isn't included: it's genuinely fixed-
pitch, so pdfdoc.py's existing flat 0.6em constant is already exact --
confirmed against this same source table, whose Corpus entries are
uniformly 153600 for every character (153600 / 256 / 1000 = 0.6).
"""

